import { Stack } from "aws-cdk-lib";
import { Template } from "aws-cdk-lib/assertions";
import { beforeAll, describe, expect, it } from "vitest";
import { CodeBuildGateDefinitionSchema } from "@agentx/contracts";
import { buildAgentXApp } from "../../infra/lib/app.js";
import { AGENTX_BETA_RELEASE_PROJECT_NAME, AGENTX_RELEASE_PROJECT_NAME } from "../../infra/lib/release-pipeline.js";
import { RELEASE_PROJECT_KEYS, environmentReleaseNames } from "../../infra/lib/environment-release-pipeline.js";
import { CI_RUNNER_PROJECT } from "../../infra/lib/ci-runner.js";
import { skipLambdaBundling } from "../support/skip-bundling.js";

skipLambdaBundling();

// The broker starts and reads CodeBuild gate projects (packages/broker/src/codebuild.ts). Which projects is data: each repository registers its own gates, and the registered name
// must match CodeBuildGateDefinitionSchema (`agentx-` + letters, digits, `_`, `-`). So the grant is a prefix, not a list. What this file pins is that the prefix reaches no project
// this repository creates (the release pipelines' and the CI runner's projects live outside it), that the grant is those two actions and nothing else, and that it is exactly the
// prefix the gate contract admits, so a change to either side is a decision, not a drift.

type Json = Record<string, unknown>;
interface Statement { Effect: string; Action?: string | string[]; Resource?: unknown }
interface TemplateJson { Resources: Record<string, { Type: string; Properties: Json }> }
const ACCOUNT = "123456789012";
const REGION = "us-east-1";
const list = <T>(value: T | T[] | undefined): T[] => (value === undefined ? [] : Array.isArray(value) ? value : [value]);

function resolve(value: unknown): string {
  if (typeof value === "string") return value;
  const node = value as Json;
  if ("Ref" in node) {
    const ref = String(node.Ref);
    return ref === "AWS::Partition" ? "aws" : ref === "AWS::Region" ? REGION : ref === "AWS::AccountId" ? ACCOUNT : `<Ref:${ref}>`;
  }
  if ("Fn::Join" in node) {
    const [separator, parts] = node["Fn::Join"] as [string, unknown[]];
    return parts.map(resolve).join(separator);
  }
  return `<${Object.keys(node).join(",")}>`;
}
const glob = (pattern: string, text: string): boolean => new RegExp(`^${pattern.replace(/[.+^${}()|[\]\\]/g, "\\$&").replaceAll("*", ".*")}$`).test(text);
const projectArn = (name: string): string => `arn:aws:codebuild:${REGION}:${ACCOUNT}:project/${name}`;

interface Grant { readonly stack: string; readonly role: string; readonly action: string; readonly resources: string[] }
const grants: Grant[] = [];
const projectNames = new Map<string, string>();
const stackNames: string[] = [];

beforeAll(() => {
  const apps = [
    buildAgentXApp({ agentxInstaller: "enabled", agentxCiRunner: "enabled" }),
    buildAgentXApp({ agentxEnv: "staging" }),
    // The named environment's own release pipeline (six projects, `rovara-staging-*`), which synthesizes alone.
    buildAgentXApp({ agentxReleasePipeline: "staging", agentxRegion: "us-west-2" }),
  ];
  for (const app of apps) {
    for (const stack of app.node.children.filter((child): child is Stack => Stack.isStack(child))) {
      stackNames.push(stack.stackName);
      const json = Template.fromStack(stack).toJSON() as TemplateJson;
      for (const [id, resource] of Object.entries(json.Resources)) {
        if (resource.Type === "AWS::CodeBuild::Project") projectNames.set(`${stack.stackName}/${id}`, resource.Properties.Name === undefined ? "<generated by CloudFormation>" : resolve(resource.Properties.Name));
        if (resource.Type !== "AWS::IAM::Policy") continue;
        const roles = list(resource.Properties.Roles).map((role) => resolve(role));
        const statements = (resource.Properties.PolicyDocument as { Statement: Statement[] }).Statement;
        for (const statement of statements) {
          if (statement.Effect !== "Allow") continue;
          for (const action of list(statement.Action).filter((a) => a.toLowerCase().startsWith("codebuild:"))) {
            grants.push({ stack: stack.stackName, role: roles.join(","), action, resources: list(statement.Resource).map(resolve) });
          }
        }
      }
    }
  }
}, 300_000);

describe("the broker's CodeBuild grant", () => {
  it("is StartBuild and BatchGetBuilds on `agentx-*` projects of this account and region, for the broker's role only (control plane, legacy and named)", () => {
    const control = grants.filter((grant) => grant.stack.endsWith("control-plane") || grant.stack === "AgentXControlPlane");
    expect(control.map((grant) => grant.action).sort()).toEqual(["codebuild:BatchGetBuilds", "codebuild:BatchGetBuilds", "codebuild:StartBuild", "codebuild:StartBuild"]);
    for (const grant of control) {
      expect(grant.role, `${grant.stack} ${grant.action}`).toMatch(/Broker/u);
      expect(grant.resources).toEqual([projectArn("agentx-*")]);
    }
    expect(new Set(control.map((grant) => grant.stack)).size).toBe(2);
  });

  it("is the one prefix the gate contract admits: a registrable gate project is allowed and an unregistrable one is not", () => {
    const [grant] = grants.filter((candidate) => candidate.action === "codebuild:StartBuild" && /Broker/u.test(candidate.role));
    const allowed = (name: string): boolean => grant!.resources.some((pattern) => glob(pattern, projectArn(name)));
    for (const name of ["agentx-website-quality", "agentx-a", "agentx-Mixed_case-1"]) {
      expect(CodeBuildGateDefinitionSchema.safeParse({ name: "quality", projectName: name, timeoutMinutes: 30 }).success, name).toBe(true);
      expect(allowed(name), name).toBe(true);
    }
    for (const name of ["release-agentx-production", "release-agentx-beta", "rovara-ci-tests", "AgentXInstaller-InstallerJob-abc", "my-agentx-project", "agentx"]) {
      expect(allowed(name), name).toBe(false);
    }
    for (const name of ["release-agentx-production", "rovara-ci-tests", "other"]) {
      expect(CodeBuildGateDefinitionSchema.safeParse({ name: "quality", projectName: name, timeoutMinutes: 30 }).success, name).toBe(false);
    }
  });

  it("reaches no CodeBuild project this repository creates: none is named `agentx-*`", () => {
    const names = [...projectNames.values()];
    expect(names).toEqual(expect.arrayContaining([AGENTX_RELEASE_PROJECT_NAME, AGENTX_BETA_RELEASE_PROJECT_NAME, CI_RUNNER_PROJECT, ...RELEASE_PROJECT_KEYS.map((key) => environmentReleaseNames("staging").project(key))]));
    expect(stackNames).toEqual(expect.arrayContaining(["AgentXInstaller", "AgentXCiRunner", "AgentXReleasePipeline"]));
    // 14 today: 2 release, 1 installer (named by CloudFormation from its stack name, `AgentXInstaller-...`, which the case-sensitive `agentx-*` pattern does not match), 1 CI runner, 10 of the environment pipeline.
    expect(names.length).toBeGreaterThanOrEqual(14);
    for (const [where, name] of projectNames) {
      expect(glob("agentx-*", name), `${where} is named ${name}`).toBe(false);
    }
    // The release projects are denied to the broker's boundary as well as left outside the prefix (legacy-runtime-boundary.test.ts, release-access-denies.test.ts).
    expect(AGENTX_RELEASE_PROJECT_NAME.startsWith("release-")).toBe(true);
    expect(AGENTX_BETA_RELEASE_PROJECT_NAME.startsWith("release-")).toBe(true);
  });
});
