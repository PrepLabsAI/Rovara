import { readFileSync } from "node:fs";
import { beforeAll, describe, expect, it } from "vitest";
import { denyNetwork } from "./model-gateway-no-network.js";
import { SnapshotPriceSource } from "../../packages/model-gateway/src/price-index.js";
import { REVIEWED_OPENROUTER_POLICIES, openRouterPolicy, openRouterHold, openRouterDecimal, type OpenRouterTariff } from "../../packages/model-gateway/src/openrouter-policy.js";
import { settleChargeAmount } from "../../packages/model-gateway/src/reported-cost.js";
import { usageCost } from "../../packages/model-gateway/src/estimate.js";
import { offeredOpenRouterModels } from "../../packages/model-gateway/src/offered-models.js";
beforeAll(denyNetwork);
// Run 2 (2026-11-24): the installable rows of OPENROUTER-V3-REPORT-2.json that passed the Opus tariff review (REVIEW-OPUS-TARIFFS-2.md), installed as-is.
// The fixture is generated by briefs/codex/openrouter-harness-v3/policies-r2/gen-rows.py from the report; the source must equal it exactly.
const fixture = JSON.parse(readFileSync(new URL("../fixtures/openrouter-reviewed-v3r2-rows.json", import.meta.url), "utf8")) as OpenRouterTariff[];
// Prices pinned by hand (USD per token) for a few rows, independent of the fixture. A sample that the review excluded is skipped.
const PINNED = {
 "anthropic/claude-haiku-5.5": { route: "amazon-bedrock", prompt: "0.0000005", completion: "0.0000025", read: "0.00000005", write: "0.000000625", enforced: false },
 "google/gemini-4-hydrogen": { route: "google-ai-studio/priority", prompt: "0.0000027", completion: "0.0000135", read: "0.000000135", write: "0.00000015", enforced: false },
 "openai/gpt-6-luna": { route: "openai/flex", prompt: "0.0000001", completion: "0.000000375", read: "0.00000001", write: "0.000000125", enforced: false },
 "qwen/qwen3.7-max": { route: "alibaba", prompt: "0.000001475", completion: "0.000004425", read: "0.000000295", write: "0.00000184375", enforced: false },
 "openai/gpt-oss-20b": { route: "akashml/fp4", prompt: "0.000000018", completion: "0.00000009", read: "0.000000009", write: "0", enforced: true },
 "z-ai/glm-4.7": { route: "novita/fp8", prompt: "0.0000006", completion: "0.0000022", read: "0.00000011", write: "0", enforced: true },
 "thinkingmachines/inkling": { route: "together", prompt: "0.000001", completion: "0.00000405", read: "0.00000017", write: "0", enforced: true },
} as const;
const rows = REVIEWED_OPENROUTER_POLICIES;
const models = fixture.map(r => r.model);
const rowOf = (model: string) => rows.find(r => r.model === model)!;
const nowFor = (model: string) => rowOf(model).verifiedAt + 1;
const store = { load: async () => undefined, save: async () => false };
const price = (model: string, now: number) => { const p = new SnapshotPriceSource(store, { now: () => now }); return p.reload().then(() => p.priceFor("openrouter", model)); };

it("installs exactly the fixture rows: sorted by model, one row per model, review evidence with the row count, no candidate label", () => {
 expect(rows.length).toBeGreaterThan(0);
 expect(rows.length).toBeLessThanOrEqual(64);
 expect(rows).toEqual(fixture);
 expect(models).toEqual([...models].sort());
 expect(new Set(models).size).toBe(rows.length);
 for (const r of rows) {
  expect(r.evidence).toBe(`Opus tariff review TARIFFS PASS ${rows.length} (OpenRouter v3 owner paid run 2 2026-11-24); briefs/codex/openrouter-harness-v3/REVIEW-OPUS-TARIFFS-2.md and OPENROUTER-V3-REPORT-2.json; installed as-is, one row per model`);
  expect(r.evidence).not.toContain("CANDIDATE");
  expect(r.max_completion_tokens).toBe(2048);
  expect(r.reasoning).toEqual({ mode: "bounded", max_tokens: 1024 });
  expect(r.expiresAt - r.verifiedAt).toBeLessThanOrEqual(86_400_000);
  expect(r.pricing.request).toBe("0");
  expect(r.pricing.internal_reasoning).toBe(r.pricing.completion);
  const enforced = r.cacheWriteBasis !== undefined;
  expect(Object.keys(r).sort()).toEqual(["evidence", "expiresAt", "max_completion_tokens", "model", "pricing", "reasoning", "route", "verifiedAt", ...(enforced ? ["cacheWriteBasis", "cacheWriteEnforcementVersion"] : [])].sort());
  // an enforced row carries the "0" write price; an explicit-write row never carries the basis
  if (enforced) { expect(r.cacheWriteBasis).toBe("never_requested_enforced"); expect(r.cacheWriteEnforcementVersion).toBe("openrouter-no-cache-write-v1"); expect(r.pricing.input_cache_write).toBe("0"); }
  else expect(openRouterDecimal(r.pricing.input_cache_write)).toBeGreaterThan(0n);
 }
 // both kinds are present in the set
 expect(rows.some(r => r.cacheWriteBasis !== undefined)).toBe(true);
 expect(rows.some(r => r.cacheWriteBasis === undefined)).toBe(true);
});

it("pins hand-written prices, routes and the cache-write kind for sample rows (an excluded sample is skipped, but both kinds must remain covered)", () => {
 const present = Object.entries(PINNED).filter(([m]) => models.includes(m));
 expect(present.some(([, s]) => s.enforced)).toBe(true);
 expect(present.some(([, s]) => !s.enforced)).toBe(true);
 for (const [model, s] of present) {
  const r = rowOf(model);
  expect(r.route, model).toBe(s.route);
  expect(r.pricing, model).toEqual({ prompt: s.prompt, completion: s.completion, internal_reasoning: s.completion, request: "0", input_cache_read: s.read, input_cache_write: s.write });
  expect(r.cacheWriteBasis === "never_requested_enforced", model).toBe(s.enforced);
 }
});

describe.each(models)("%s", model => {
 const spec = () => { const r = rowOf(model); return { prompt: r.pricing.prompt, completion: r.pricing.completion, read: r.pricing.input_cache_read, write: r.pricing.input_cache_write }; };
 it("validates now, resolves to exactly one row, and refuses before verification and at and after expiry", () => {
  const r = rowOf(model);
  expect(rows.filter(x => x.model === model)).toHaveLength(1);
  expect(openRouterPolicy(model, nowFor(model))).toMatchObject({ model, route: r.route });
  expect(openRouterPolicy(model, r.verifiedAt - 1)).toBeUndefined();
  expect(openRouterPolicy(model, r.expiresAt - 1)).toBeDefined();
  expect(openRouterPolicy(model, r.expiresAt)).toBeUndefined();
  expect(openRouterPolicy(model, r.expiresAt + 3_600_000)).toBeUndefined();
  // a second row for the same model switches the model off
  expect(openRouterPolicy(model, nowFor(model), [r, { ...r, route: "other" }])).toBeUndefined();
 });
 it("never charges less than the token cost at the row prices (reported cost absent, 0, 1, 10x)", async () => {
  const s = spec();
  const resolved = (await price(model, nowFor(model)))!;
  expect(resolved).toBeDefined();
  const usd = (n: number, p: string) => openRouterDecimal(p) * BigInt(n);
  const usages = [{ input: 1000, output: 500, cacheRead: 0, cacheWrite: 0 }, { input: 12_345, output: 2048, cacheRead: 800, cacheWrite: 300 }, { input: 1, output: 1, cacheRead: 0, cacheWrite: 0 }];
  for (const usage of usages) {
   // independent token cost: cache writes at max(prompt, write), cache read at read, output at completion
   const writeRate = openRouterDecimal(s.write) > openRouterDecimal(s.prompt) ? s.write : s.prompt;
   const exact = usd(usage.input, s.prompt) + usd(usage.cacheRead, s.read) + usd(usage.cacheWrite, writeRate) + usd(usage.output, s.completion);
   const floorMicros = Number((exact * 1_000_000n) / 10n ** 18n);
   expect(usageCost(usage, resolved)).toBeGreaterThanOrEqual(floorMicros);
   for (const reportedCostMicros of [undefined, 0, 1, floorMicros * 10 + 7]) {
    const out = settleChargeAmount({ usage, price: { ...resolved, estimated: false }, reservationMicros: 1, ...(reportedCostMicros === undefined ? {} : { reportedCostMicros }) });
    expect(out.actualMicros).toBeGreaterThanOrEqual(floorMicros);
    expect(out.actualMicros).toBeGreaterThanOrEqual(reportedCostMicros ?? 0);
   }
  }
 });
 it("holds the worst case: ceiling output at the row's rate plus every prompt token as a cache write", () => {
  const s = spec();
  const hold = openRouterHold(openRouterPolicy(model, nowFor(model))!, 500, 2048);
  const exact = BigInt(500) * (openRouterDecimal(s.prompt) + openRouterDecimal(s.write)) + BigInt(2048) * openRouterDecimal(s.completion);
  expect(hold).toBeGreaterThanOrEqual(Number((exact * 1_000_000n) / 10n ** 18n));
 });
 it("is refused once expired by the price source, and offered only while fresh", async () => {
  const r = rowOf(model);
  expect(await price(model, r.expiresAt)).toBeUndefined();
  expect(await price(model, r.verifiedAt - 1)).toBeUndefined();
  expect(offeredOpenRouterModels(rows, nowFor(model))).toContain(model);
  expect(offeredOpenRouterModels(rows, r.expiresAt)).not.toContain(model);
 });
});

it("refuses any model that is not in the reviewed set, including the 5 run-1 rows that are not in run 2", async () => {
 const now = Math.max(...rows.map(r => r.verifiedAt)) + 1;
 for (const model of ["qwen/qwen3.8-2.4t-a95b", "anthropic/claude-haiku-5.4", "openai/gpt-6.2-astra-pro", "x-ai/grok-4.7", "google/gemini-4-neon", "openai/gpt-5-nano", "vendor/unreviewed"]) {
  expect(models).not.toContain(model);
  expect(openRouterPolicy(model, now)).toBeUndefined();
  expect(await price(model, now)).toBeUndefined();
  expect(offeredOpenRouterModels(rows, now)).not.toContain(model);
 }
 // exactly one route per model is installed; the offered list is the whole set while every row is fresh (64 at most, so no cap drops one)
 expect(offeredOpenRouterModels(rows, now).sort()).toEqual([...models].sort());
 // the run-1 gemini row (expired 2026-11-24 19:52Z) and every run-1 evidence string are gone
 expect(rows.every(r => !r.evidence.includes("TARIFFS PASS 5 "))).toBe(true);
});

it("hashes the price: a changed price changes the policy hash", () => {
 const r = rows[0]!; const now = nowFor(r.model);
 const base = openRouterPolicy(r.model, now, [r])!.hash;
 expect(openRouterPolicy(r.model, now, [{ ...r, pricing: { ...r.pricing, completion: "0.0000024" } }])!.hash).not.toBe(base);
});
