import { beforeAll, expect, it } from "vitest";
import { denyNetwork } from "./model-gateway-no-network.js";
import { chargeReceipt } from "./model-gateway-charge-receipt-fixture.js";
import { InMemoryMeter } from "../../packages/model-gateway/src/meter.js";
import { DynamoMeter } from "../../packages/model-gateway/src/dynamo-meter.js";
import { Dynamo } from "../../packages/model-gateway/src/dynamo.js";
import { WireDynamo } from "./model-gateway-wire-dynamo.js";
beforeAll(denyNetwork);
const tables = { meter: "meter", ledger: "ledger", markers: "markers" };
const scope = { iss: "https://install.example/v1/auth", cid: `org_${"a".repeat(20)}`, pid: "web", tid: "task_1" };
const caps = { task: 200, projectMonth: 200, companyMonth: 200 };
for (const adapter of ["memory", "dynamo"]) it(`${adapter}: revisioned receipts replace original-month exposure once and reject conflicting replay`, async () => {
  let now = Date.parse("2026-01-31T23:59:00.000Z");
  const wire = new WireDynamo(Object.values(tables));
  const db = new Dynamo({ region: "us-west-2", credentials: async () => ({ accessKeyId: "TEST", secretAccessKey: "not-real" }), transport: wire.transport });
  const meter = adapter === "memory" ? new InMemoryMeter(() => now) : new DynamoMeter({ db, tables, now: () => now });
  const settle = Reflect.get(meter, "settleV2")?.bind(meter) as (v: unknown) => Promise<unknown>;
  const apply = Reflect.get(meter, "applyChargeReceipt")?.bind(meter) as (v: unknown) => Promise<unknown>;
  expect(settle).toBeTypeOf("function"); expect(apply).toBeTypeOf("function");
  const r = await meter.reserve({ scope, caps, estimateMicros: 80 }); if (!r.ok) throw new Error("reserve");
  const first = chargeReceipt({ callId: r.reservation.id });
  await settle({ reservationId: r.reservation.id, receipt: first });
  expect((await meter.read(scope)).every(r => r.spentMicros === 80 && r.estimatedMicros === 80 && r.committed === 80 && r.reservedMicros === 0)).toBe(true);
  now = Date.parse("2026-02-02T00:00:00.000Z");
  const final = { ...first, revision: 2, replacesRevision: 1, status: "final", reason: "reported_cost", amountMicros: { state: "available", value: 30 }, providerCostMicros: { state: "available", value: 30 }, recordedAt: new Date(now).toISOString() };
  expect(await apply(final)).toMatchObject({ result: "applied", deltaMicros: -50 });
  expect(await apply(final)).toMatchObject({ result: "duplicate", deltaMicros: 0 });
  expect(await apply(first)).toMatchObject({ result: "older" });
  await expect(apply({ ...final, amountMicros: { state: "available", value: 31 } })).rejects.toThrow();
  expect(await apply({ ...final, revision: 3, replacesRevision: 2, amountMicros: { state: "available", value: 90 }, providerCostMicros: { state: "available", value: 90 } })).toMatchObject({ deltaMicros: 60 });
  const feb = await meter.read(scope);
  expect(feb.find(r => r.item === "project")).toMatchObject({ spentMicros: 0 });
  expect(feb.find(r => r.item === "task")).toMatchObject({ spentMicros: 90, estimatedMicros: 0 });
  now = Date.parse(first.occurredAt);
  expect((await meter.read(scope)).every(r => r.spentMicros === 90 && r.estimatedMicros === 0 && r.committed === 90)).toBe(true);
  if (adapter === "dynamo") expect(wire.items(tables.ledger).filter(r => String(r.sk).startsWith("ADJUST#"))).toHaveLength(3);
});
for (const adapter of ["memory", "dynamo"]) it(`${adapter}: a receipt-bound hold refuses a legacy settle and keeps the hold intact`, async () => {
  const at = Date.parse("2026-01-31T23:59:00.000Z");
  const wire = new WireDynamo(Object.values(tables));
  const db = new Dynamo({ region: "us-west-2", credentials: async () => ({ accessKeyId: "TEST", secretAccessKey: "not-real" }), transport: wire.transport });
  const meter = adapter === "memory" ? new InMemoryMeter(() => at) : new DynamoMeter({ db, tables, now: () => at });
  const receipt = chargeReceipt();
  const held = await meter.reserve({ scope, caps, estimateMicros: 80, charge: { receipt, requestFingerprint: "a".repeat(64) } });
  if (!held.ok) throw new Error("reserve");
  await expect(meter.settle(held.reservation, 0)).rejects.toThrow("charge receipt required");
  expect((await meter.read(scope)).every(row => row.reservedMicros === 80 && row.spentMicros === 0)).toBe(true);
  await meter.settleV2({ reservationId: held.reservation.id, receipt });
  expect((await meter.read(scope)).every(row => row.reservedMicros === 0 && row.spentMicros === 80)).toBe(true);
});
