/**
 * The MIDSTEP-2 carrier test (CI "option A"): tests/fixtures/e2e-midstep-carriers is an app that, when the page asks mid-step, acquires a session cookie (Set-Cookie), a local storage token, a
 * session storage token, a token inside a JSON blob, a `?token=` URL, an Authorization-header call, an IndexedDB token and one opaque id under a neutral key. This module plans the cases,
 * plants values that were generated for this run only, drives the scripted model, and judges what the model-bound transcripts held. It is shared by the Docker test (tests/linux), the
 * executor-on-this-machine test and the Docker-free harness test.
 *
 * Nothing planted here is written outside a temp directory: the values are generated by `plantCarrierSets` for each run and reach the fixture app only through a file in the run's temp
 * directory (an owned mount in Docker).
 */
export const CARRIERS_ROOT = join(import.meta.dirname, "../fixtures/e2e-midstep-carriers");
/** The files a candidate carries: what the app runs from. */
export const CARRIERS_APP_FILES = ["package.json", "server.mjs", "seed.mjs", "public"];
export const CARRIER_ACCOUNT_PROFILE = "orders-owner";

/** One case per name. `control` shows nothing secret after the sync; `weak` shows the opaque id; every other name shows the value of that carrier. */
export const CARRIER_NAMES = ["control", "cookie", "local", "session", "json", "url", "bearer", "idb", "weak"] as const;
export type CarrierName = (typeof CARRIER_NAMES)[number];
export const STRONG_CARRIERS = ["cookie", "local", "session", "json", "url", "bearer", "idb"] as const;
export type StrongCarrier = (typeof STRONG_CARRIERS)[number];
/** The route allows three agent steps in one group, so the nine cases run as three groups of three (one Docker run each). */
export const CARRIER_GROUPS: ReadonlyArray<readonly CarrierName[]> = [["control", "cookie", "local"], ["session", "json", "url"], ["bearer", "idb", "weak"]];

/** What the app issues in one case: seven credentials and one opaque id. Every case has its own set, so a value one case taught the run cannot refuse another case's call. */
export type PlantedSet = Readonly<Record<StrongCarrier | "weak", string>>;

const mixed = (text: string) => /[0-9]/.test(text) && /[a-z]/.test(text) && /[A-Z]/.test(text);
/** A random 43-character base64url token with digits and both cases (the shape of the accounts app's own session cookie), so that no run depends on a lucky draw. */
function strongToken(): string { for (;;) { const value = randomBytes(32).toString("base64url"); if (mixed(value)) return value; } }
/** A standard-base64 token with `+` or `/` in it, so its percent-encoded spelling differs from the plain one. */
function urlToken(): string { for (;;) { const value = randomBytes(33).toString("base64"); if (mixed(value) && /[+/]/.test(value) && !value.startsWith("/")) return value; } }
/** The weak-echo fixture's shape: an opaque 20-character id (letters and digits) that is app data, kept under a neutral key. */
function opaqueId(): string { for (;;) { const value = `Doc${randomBytes(12).toString("hex").slice(0, 17)}`; if (/[0-9]/.test(value) && /[a-f]/.test(value.slice(3))) return value; } }

export function plantCarrierSets(names: readonly CarrierName[]): Record<string, PlantedSet> {
  return Object.fromEntries(names.map((name) => [name, { cookie: strongToken(), local: strongToken(), session: strongToken(), json: strongToken(), url: urlToken(), bearer: strongToken(), idb: strongToken(), weak: opaqueId() }]));
}

/** The value a case's page shows after the sync; null for the control. */
export const shownValue = (name: CarrierName, set: PlantedSet): string | null => (name === "control" ? null : set[name]);
/** Every value of every set, strong first. */
export const everyPlanted = (sets: Record<string, PlantedSet>): string[] => Object.values(sets).flatMap((set) => Object.values(set));

/**
 * Every common spelling of a value that could appear in a transcript: plain, percent-encoded, double percent-encoded, hex, and base64 or base64url of it as the start of a text and as
 * a part of a longer one (the three byte alignments). A spelling is a text to look for, so each is long enough to be unique.
 */
export function spellings(value: string): string[] {
  const forms = new Set<string>([value, encodeURIComponent(value), encodeURIComponent(encodeURIComponent(value)), Buffer.from(value, "utf8").toString("hex")]);
  for (let shift = 0; shift < 3; shift += 1) {
    const encoded = Buffer.from(`${"x".repeat(shift)}${value}`, "utf8").toString("base64");
    const core = encoded.slice(shift === 0 ? 0 : 4, -4);
    forms.add(core);
    forms.add(core.replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/, ""));
  }
  return [...forms].filter((form) => form.length >= 12);
}

export const carrierGoal = (name: CarrierName): string => (name === "control" ? "Press the button that syncs quietly" : `Press the button that syncs and shows the ${name} value`);
/**
 * Tap the sync button, tap it once more, then conclude. The second tap is a safety margin, not a second test: the agent loop reads the screen again as soon as the page changes shape and holds
 * still for two reads, and on a slow host that can be before the app's async sync has printed its result. The sync is idempotent (the app issues the same set again), so whichever read first
 * shows the result, the model-bound call that shows it is the one under test, and a read before it is a call that shows nothing synced.
 */
export const carrierScript = (name: CarrierName): readonly ScriptedTurn[] => {
  const tap: ScriptedTurn = { kind: "tap", name: name === "control" ? /^Sync quietly$/ : new RegExp(`^Sync and show ${name}$`) };
  return [tap, tap, { kind: "done" }];
};

const carrierScenario = (name: CarrierName) => (targetId: string): E2EScenario => ({ scenarioId: `carrier-${name}`, requirementId: `carrier-${name}-requirement`, requestedTargetIds: [targetId], required: true,
  accountProfileId: CARRIER_ACCOUNT_PROFILE, minimumEvidence: "runtime", requiredRealComponentIds: [],
  steps: [{ kind: "navigate", path: "/" }, { kind: "agent", goal: carrierGoal(name), maxActions: 4 }], assertions: [{ kind: "visible", testId: "panel", equals: true }] });

/** The plan of one group: one case per name (all under the owner account, so one shard), each with one agent step under the scripted route. `carriersFile` is where the app reads the sets from. */
export function createCarrierPlan(names: readonly CarrierName[], carriersFile: string): WebApiProbePlan {
  return createWebApiProbePlan({ probe: "web-csv-positive-v1", appRoot: CARRIERS_ROOT, modelRoute: SCRIPTED_ROUTE, routeLimits: SCRIPTED_ROUTE_LIMITS, healthTimeoutMs: 20_000, recipeStart: { env: { CARRIERS_FILE: carriersFile } },
    accountScenarios: names.map((name) => ({ accountProfileId: CARRIER_ACCOUNT_PROFILE, scenario: carrierScenario(name) })) });
}

/** The scripted model of a group, recording the call exactly as the provider would have received it (after the worker's checks and its own shaping), so a leak is judged on that and not only on the worker's redacted copy. */
export function createCarrierModel(names: readonly CarrierName[]): { invoke: E2EInvoke; providerCalls: string[] } {
  const providerCalls: string[] = [];
  const scripted = createScriptedE2EInvoke({ scripts: Object.fromEntries(names.map((name) => [sha256Hex(carrierGoal(name)), carrierScript(name)])) });
  return { providerCalls, invoke: async (input) => { providerCalls.push(JSON.stringify(input.call)); return scripted(input); } };
}

