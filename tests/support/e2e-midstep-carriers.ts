export const transcriptText = (transcript: E2EModelTranscript): string => `${transcript.prompt ?? ""}\n${transcript.response ?? ""}`;

/** Which planted values (labelled `case/carrier`, never the values themselves) appear in `texts` in any spelling. */
export function leaks(sets: Record<string, PlantedSet>, texts: readonly string[]): string[] {
  const found: string[] = [];
  for (const [name, set] of Object.entries(sets)) {
    for (const [carrier, value] of Object.entries(set)) {
      if (spellings(value).some((form) => texts.some((text) => text.includes(form)))) found.push(`${name}/${carrier}`);
    }
  }
  return found;
}

/** The agent step the ledger records for a case (a case here has exactly one), or null when there is no ledger. */
export function ledgerStepOf(outDir: string, caseId: string): { verdict: string; stopCode: string | null; actions: Array<{ tool: string; outcome: string; name: string | null }> } | null {
  const path = join(outDir, E2E_AGENT_EVIDENCE_DIR, agentCaseDirectoryName(caseId), E2E_AGENT_LEDGER_FILE);
  if (!existsSync(path)) return null;
  const step = E2EAgentActionLedgerSchema.parse(JSON.parse(readFileSync(path, "utf8"))).steps[0];
  return step === undefined ? null : { verdict: step.verdict, stopCode: step.stopCode, actions: step.actions.map((action) => ({ tool: action.tool, outcome: action.outcome, name: action.node?.name ?? null })) };
}
