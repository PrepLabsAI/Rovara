const freePort = (): Promise<number> => new Promise((resolve, reject) => {
  const server = createServer();
  server.once("error", reject);
  server.listen(0, "127.0.0.1", () => { const { port } = server.address() as { port: number }; server.close(() => resolve(port)); });
});

export type CarriersAppProcess = Readonly<{ upstream: string; directory: string; stop(): Promise<void> }>;

/** The accounts file the host writes for a plan (`rovara-accounts/v1`): each planned account with the tenant and role its profile declares. */
export function accountsFileFor(fixture: WebApiProbePlan): string {
  const applicationId = fixture.compiled.originByApplicationId[0]!.applicationId;
  const contract = readE2EApplicationProjectContract(fixture.compiled.runtimeAdmissionContext.selectionInput.sourceSnapshot, applicationId)!;
  return JSON.stringify({ schemaVersion: "rovara-accounts/v1", accounts: fixture.plan.accounts.map((account) => {
    const profile = contract.accountProfiles.find((item) => item.profileId === account.profileId)!;
    return { profileId: account.profileId, email: account.email, password: account.password, tenantRef: profile.tenantRef, roleRef: profile.roleRef };
  }) });
}

/** The accounts file, the seed command run for real, and the app on a loopback port reading the sets from a file in its own temp directory (the host's owned mount, here). */
export async function startCarriersApp(accountsJson: string, sets: Record<string, PlantedSet>, carriersFile?: string): Promise<CarriersAppProcess> {
  const directory = await realpath(await mkdtemp(join(tmpdir(), "carriers-app-")));
  const app = join(directory, "app");
  await mkdir(app, { recursive: true });
  for (const file of CARRIERS_APP_FILES) await cp(join(CARRIERS_ROOT, file), join(app, file), { recursive: true });
  const accountsFile = join(directory, "rovara-accounts.json");
  await writeFile(accountsFile, accountsJson, { mode: 0o600 });
  const data = join(directory, "data");
  await mkdir(data);
  const file = carriersFile ?? join(directory, "carriers.json");
  await writeFile(file, JSON.stringify(sets), { mode: 0o600 });
  const env = { PATH: process.env.PATH ?? "", ROVARA_ACCOUNTS_FILE: accountsFile, ROVARA_DATA_DIR: data, CARRIERS_FILE: file };
  execFileSync(process.execPath, ["seed.mjs"], { cwd: app, env, stdio: "pipe" });
  const port = await freePort();
  const child: ChildProcess = spawn(process.execPath, ["server.mjs"], { cwd: app, env: { ...env, APP_PORT: String(port) }, stdio: "ignore" });
  const upstream = `http://127.0.0.1:${port}`;
  for (let attempt = 0; attempt < 100; attempt += 1) {
    try { if ((await fetch(`${upstream}/health`)).status === 200) break; } catch { /* not listening yet */ }
    await new Promise((resolve) => setTimeout(resolve, 100));
  }
  return { upstream, directory, async stop() { child.kill("SIGKILL"); await rm(directory, { recursive: true, force: true }); } };
}

