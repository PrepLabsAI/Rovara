const sandboxed = async (request: { runId: string; groupId: string }) => ({ schemaVersion: "e2e-executor-chromium-sandbox/v1" as const, runId: request.runId, groupId: request.groupId,
  browser: { pid: 40, nsPidDepth: 1, seccompFilters: 1, uidMap: "0 0 4294967295" }, renderers: [{ pid: 41, nsPidDepth: 2, seccompFilters: 2, uidMap: "0 1000 1" }] });

/** Runs one group of cases through the real executor, the pinned CLI and a real Chromium on this machine, the worker's real model proxy answering from the scripted double. */
export async function runCarrierGroupLocally(names: readonly CarrierName[], options: { timeoutMs?: number } = {}): Promise<CarrierRun & { cleanup(): Promise<void> }> {
  const sets = plantCarrierSets(names);
  const dir = realpathSync(await mkdtemp(join(tmpdir(), "carriers-run-")));
  const fixture = createCarrierPlan(names, join(dir, "carriers.json"));
  const app = await startCarriersApp(accountsFileFor(fixture), sets, join(dir, "carriers.json"));
  // A unix socket path must stay under about 100 bytes: a short directory.
  const socketDir = realpathSync(mkdtempSync("/tmp/rvc-"));
  const evidence = createE2EModelEvidenceCollector();
  const { invoke, providerCalls } = createCarrierModel(names);
  const session = await openE2EModelChannelSession({ runId: fixture.plan.runId, modelRoute: SCRIPTED_ROUTE, policyScope: "standard", socketPath: join(socketDir, "m.sock"),
    allowedSteps: e2eApplicationGroupAgentSteps(fixture.compiled), credentialSet: { passwords: fixture.plan.accounts.map((item) => item.password), emails: fixture.plan.accounts.map((item) => item.email), cookieValues: [] },
    deadlineAt: fixture.plan.deadlineAt, dayBudget: createInMemoryE2EDayBudget(), evidence, signal: new AbortController().signal, environment: { ROVARA_E2E_SCRIPTED_MODEL: "1" }, invoke });
  const out = join(dir, "out");
  await writeFile(join(dir, "plan.json"), JSON.stringify(withModelChannel(fixture.plan, "5a".repeat(32))));
  const result = await runE2EExecutor({ planPath: join(dir, "plan.json"), outDir: out, signal: AbortSignal.timeout(options.timeoutMs ?? 280_000), localAppUpstream: app.upstream,
    inspectChromiumSandbox: sandboxed, chromiumSandboxSettleMs: 0, modelSocketPath: session.socketPath });
  const summary = await session.close();
  const log = existsSync(join(out, "executor.log")) ? readFileSync(join(out, "executor.log"), "utf8") : "(no executor log)";
  return { names, sets, fixture, outDir: out, exitCode: result.exitCode, reason: result.reason, receipts: summary.receipts, transcripts: evidence.transcripts(), providerCalls, why: () => `executor exit ${String(result.exitCode)} (${String(result.reason)})\n${log}`,
    async cleanup() { await app.stop(); await rm(dir, { recursive: true, force: true }); await rm(socketDir, { recursive: true, force: true }); } };
}

