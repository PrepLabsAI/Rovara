export type CarrierRun = Readonly<{
  names: readonly CarrierName[]; sets: Record<string, PlantedSet>; fixture: WebApiProbePlan;
  /** The kept copy of the run's out directory. */
  outDir: string; exitCode: number | null; reason: string | null;
  receipts: E2EModelReceipt[]; transcripts: E2EModelTranscript[];
  /** Each call as the provider (the scripted double) received it, in order. */
  providerCalls: string[];
  /** Why the run did what it did, for a failure message. */
  why(): string;
}>;

