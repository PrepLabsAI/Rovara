// The helper launcher (test services, TS14; design test-services.md 4.0.6 and 4.1.4; deferred check TS-RN-3). It starts the real software and Rovara's own helpers that a run's dependencies need, on the run's services
// network (run-network.ts), under ONE fixed hardening profile, waits for them to answer, and removes them again. DEPLOYMENT CODE: nothing here has been run against Docker (this build starts no Docker); the Linux checks
// TS-L1 to TS-L4 and TS-L6 MUST pass on linux-runtime or a staging worker before the `tx` switch is turned on. Nothing calls this module yet.
//
// What reaches a docker argument, and from where (the rule of setup-network.ts, kept): the profile is code in this file; the image, the user, the limits, the tmpfs mounts, the ports and the fixed start-up arguments come from
// the catalog entry, which is parsed again here (a forged entry never starts); names are hashes; addresses are numbers of the run's slot; aliases and ids are matched against strict patterns first. No repository string is ever a
// docker option or a program argument: the only text from a repository that gets near one is a dependency's alias (HELPER_ALIAS_PATTERN, never a reserved name) and the user, database and file names it asks for, which are
// matched against plain patterns before they are written into a file Docker reads (the env file: one `NAME=value` per line, so a value with a line break is refused) or into a mount.
//
// The profile (4.1.4): a non-root user from the entry, `--cap-drop ALL` and no `--cap-add` (the catalog has no capability field, so a helper never has one), `no-new-privileges`, Docker's default seccomp, a read-only root where
// the entry says so with named tmpfs mounts (noexec, nosuid, nodev, owned by the helper's user), `--init`, memory equal to memory-plus-swap, CPUs and pids, a bounded local log, `--pull=never` with an image reference by
// digest (registry, the entry's repository and `@sha256:`), the services network ONLY at the address the run-network plan gives it, its aliases, and the run's four labels. No published port, no host network, no Docker
// socket, no device, no host mount except read-only files of the run's own directory. A port below 1024 gets the one namespaced sysctl that lets a non-root user bind it.
//
// Secrets: a helper's per-run user and password (generated by the caller, registered with the redactor) go into an env file the HelperFiles seam writes on a tmpfs (mode 0600), passed with `--env-file` and removed as soon as
// `docker run` has returned; a cache that has no password variable gets a config file instead (mounted read-only, removed once the helper is healthy). Neither ever appears in an argument. The seam is `HelperFiles`
// (TS15's env channel gives the worker its tmpfs implementation).
//
// RULES (the doc comment of run-network.ts, TS-RN-3): (1) ALL four labels of `net.labelArgs()` go to every `docker run`, helpers and probes; (2) every alias is validated before `--network-alias`; (3) the worker-start sweep
// is `sweepServicesNetworksAtWorkerStart`, which the worker calls once when it starts.
//
// Health: a `command` check runs a fixed command inside the helper (`docker exec`). A `tcp` or `http` check is asked from a probe container of its own on the services network (service-probe.ts): the boot firewall drops
// every packet from an `rvi*` bridge to the host, so the worker cannot ask it itself. A start that fails, or health that does not arrive within the entry's `startTimeoutS` (and the run-wide 120 s), ends the start with one
// fixed sentence; Docker's own words are never repeated. Everything started is removed.
