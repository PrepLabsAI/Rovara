interface Plan {
  request: HelperRequest;
  index: number;
  entry: CatalogEntry;
  name: string;
  address: string;
  aliases: string[];
  prepared: Prepared;
  image: string;
  /** The files mounted into the helper: the request's own, and a fake's fixture set. */
  files: readonly HelperFile[];
  /** A helper that runs a program of the worker's own image: the program's arguments, all built here from numbers and checked values (the image's entrypoint is replaced by node). */
  program?: string[];
}

function refused(request: { name?: unknown; id?: unknown }): HelperStartError {
  const name = typeof request.name === "string" ? plainName(request.name) : "a service";
  return new HelperStartError("refused", `${name} cannot be started here`, typeof request.id === "string" && TestEnvDependencyIdSchema.safeParse(request.id).success ? request.id : undefined);
}

/**
 * The fake server's program arguments and its fixture file, from the request and the run's network. Every value is a number (an address of the run's slot, the port of the catalog entry), a digest, or a fixed word: nothing a
 * repository wrote. The caller is exactly one address, the one of the sandbox the phase serves (4.0.2): the working sandbox's for the coding phase, the check sandbox's for a sealed round.
 */
function fakeProgram(net: ServicesNetwork, fake: FakeHelperRequest, address: string, port: number | undefined): { file: HelperFile; program: string[] } {
  if ((fake.phase !== "working" && fake.phase !== "check") || !FIXTURE_DIGEST.test(fake.digest) || typeof fake.fixtureJson !== "string" || port === undefined) throw new RangeError("fake");
  const caller = fake.phase === "working" ? net.workingSandboxIp : net.checkSandboxIp;
  if (!/^\d{1,3}(?:\.\d{1,3}){3}$/u.test(caller) || !/^\d{1,3}(?:\.\d{1,3}){3}$/u.test(address)) throw new RangeError("fake");
  return {
    file: { name: "fixture.json", content: fake.fixtureJson, to: FAKE_FIXTURE_TARGET },
    program: [FAKE_HELPER_ENTRY, "--listen", address, "--port", String(port), "--caller", caller, "--digest", fake.digest, "--unmatched", "fail", "--fixture", FAKE_FIXTURE_TARGET, "--ledger", FAKE_LEDGER_TARGET],
  };
}

/** Checks every request and builds its plan; nothing is started or written before this has passed for all of them. */
function planHelpers(net: ServicesNetwork, input: StartHelpersInput): Plan[] {
  if (!REGISTRY.test(input.registry) || input.registry.length > 120 || Number(/:([0-9]{1,5})(?:\/|$)/u.exec(input.registry)?.[1] ?? 0) > 65_535) throw new HelperStartError("refused", "The test services cannot be started here");
  if (!IMAGE_REFERENCE.test(input.probeImage)) throw new HelperStartError("refused", "The test services cannot be started here");
  if (input.edition !== "public" && input.edition !== "enterprise") throw new HelperStartError("refused", "The test services cannot be started here");
  if (!Number.isSafeInteger(input.maxMemMiB) || input.maxMemMiB < 1) throw new HelperStartError("refused", "The test services cannot be started here");
  if (input.helpers.length > MAX_HELPERS_PER_RUN) throw new HelperStartError("over_limit", `A run may start at most ${String(MAX_HELPERS_PER_RUN)} test services`);
  const ids = new Set<string>();
  const aliasesSeen = new Set<string>();
  const plans: Plan[] = [];
  for (const [index, request] of input.helpers.entries()) {
    try {
      if (!TestEnvDependencyIdSchema.safeParse(request.id).success || ids.has(request.id)) throw new RangeError("id");
      ids.add(request.id);
      const parsed = CatalogEntrySchema.safeParse(request.entry);
      if (!parsed.success) throw new RangeError("entry");
      const entry = parsed.data;
      // Only pinned, current, offered entries of a family this launcher knows; Rovara's own helpers (the DNS helper, the proxy) are started by the code that owns them, never as a dependency.
      // The one exception is the fake server (slice 3): a helper that runs from the worker's own image, so it has no digest, and it must come with the fake request that says what it serves (and no other entry may).
      const isFake = entry.backing === "fake" && entry.family === "fake-server" && entry.workerImage === true && entry.image.digest === undefined;
      if (entry.status === "retired" || (entry.backing === "helper" && !isFake) || !entry.editions.includes(input.edition) || (entry.image.digest === undefined && !isFake) || isFake !== (request.fake !== undefined)) throw new RangeError("entry");
      const rule = FAMILY_RULES[entry.family];
      if (rule === undefined) throw new RangeError("family");
      const aliases = [...(request.aliases ?? entry.connect.defaultAliases)];
      if (aliases.length > 4) throw new RangeError("aliases");
      for (const alias of aliases) {
        if (!HELPER_ALIAS_PATTERN.test(alias) || HELPER_RESERVED_ALIASES.includes(alias) || aliasesSeen.has(alias)) throw new RangeError("alias");
        aliasesSeen.add(alias);
      }
      const region = request.region ?? "us-east-1";
      if (!REGION.test(region)) throw new RangeError("region");
      const address = net.helperIp(index);
      const prepared = rule.prepare({ credentials: request.credentials ?? {}, address, region, aliases, port: entry.run.ports[0] ?? 4566, awsServices: request.awsServices });
      const fake = request.fake === undefined ? undefined : fakeProgram(net, request.fake, address, entry.run.ports[0]);
      const files: HelperFile[] = [...(request.files ?? []), ...(fake === undefined ? [] : [fake.file])];
      for (const [fileIndex, file] of files.entries()) {
        if (fileIndex >= MAX_FILES_PER_HELPER || !FILE_NAME.test(file.name) || RESERVED_FILE_NAMES.includes(file.name) || Buffer.byteLength(file.content) > (fake !== undefined && file === fake.file ? FAKE_FIXTURE_MAX_BYTES : MAX_FILE_BYTES)) throw new RangeError("file");
        const segments = file.to.split("/");
        if (!MOUNT_TARGET.test(file.to) || segments.includes("..") || FORBIDDEN_MOUNT_ROOTS.some((root) => file.to === `/${root}` || file.to.startsWith(`/${root}/`)) || file.to.endsWith(".sock")) throw new RangeError("file");
      }
      plans.push({ request, index, entry, name: plainName(request.name), address, aliases, prepared, files, image: fake === undefined ? `${input.registry}/${entry.image.repository}@sha256:${entry.image.digest}` : input.probeImage, ...(fake === undefined ? {} : { program: fake.program }) });
    } catch (error) {
      if (error instanceof HelperStartError) throw error;
      throw refused(request);
    }
  }
  for (const plan of plans) {
    for (const dependency of plan.request.dependsOn ?? []) if (!ids.has(dependency) || dependency === plan.request.id) throw refused(plan.request);
  }
  const totalMemMiB = plans.reduce((sum, plan) => sum + plan.entry.resources.memMiB, 0);
  if (totalMemMiB > input.maxMemMiB) throw new HelperStartError("over_limit", `The test services need ${String(totalMemMiB)} MiB; this run may use ${String(input.maxMemMiB)} MiB`);
  return plans;
}

/** The plans in start order, grouped in levels: a level starts once the one before it is healthy. A cycle is refused. */
function startLevels(plans: readonly Plan[]): Plan[][] {
  const remaining = new Map(plans.map((plan) => [plan.request.id, plan]));
  const done = new Set<string>();
  const levels: Plan[][] = [];
  while (remaining.size > 0) {
    const level = [...remaining.values()].filter((plan) => (plan.request.dependsOn ?? []).every((dependency) => done.has(dependency)));
    if (level.length === 0) throw refused([...remaining.values()][0]!.request);
    for (const plan of level) { remaining.delete(plan.request.id); }
    for (const plan of level) done.add(plan.request.id);
    levels.push(level);
  }
  return levels;
}

// ---- the arguments

function mount(host: string, to: string): string[] {
  if (!HOST_PATH.test(host) || host.split("/").includes("..") || host.includes("//")) throw new RangeError("a run file path");
  return ["-v", `${host}:${to}:ro`];
}

/** The `docker run` arguments of one helper. Pure; every input has been checked by `planHelpers` (and the pieces that come from the files seam are checked again here). */
function runArgs(net: ServicesNetwork, plan: Plan, container: string, paths: { env?: string; config?: string; files: Array<{ path: string; to: string }> }): string[] {
  const entry = plan.entry;
  const [uid, gid] = entry.run.user.split(":");
  const lowestPort = Math.min(...entry.run.ports, 65_535);
  return [
    "run", "--detach", "--name", container, "--pull=never", "--init",
    ...net.labelArgs(),
    "--network", net.name, "--ip", plan.address, ...plan.aliases.flatMap((alias) => ["--network-alias", alias]),
    "--user", entry.run.user, "--cap-drop", "ALL", "--security-opt", "no-new-privileges",
    ...(entry.run.readOnlyRoot ? ["--read-only"] : []),
    ...(lowestPort < 1024 ? ["--sysctl", `net.ipv4.ip_unprivileged_port_start=${String(lowestPort)}`] : []),
    "--memory", `${String(entry.resources.memMiB)}m`, "--memory-swap", `${String(entry.resources.memMiB)}m`, "--cpus", String(entry.resources.cpus), "--pids-limit", String(entry.resources.pids),
    // Docker's local log driver compresses rotated files by default and refuses compression with one file ("compression cannot be enabled when max file count is 1"), which fails `docker run` at start: compress=false is required.
    "--log-driver", "local", "--log-opt", "max-size=1m", "--log-opt", "max-file=1", "--log-opt", "compress=false",
    ...entry.run.tmpfs.flatMap((tmpfs) => ["--tmpfs", `${tmpfs.path}:rw,nosuid,nodev,noexec,size=${String(tmpfs.sizeMiB)}m,uid=${uid!},gid=${gid!}`]),
    ...(paths.config === undefined ? [] : mount(paths.config, plan.prepared.config!.to)),
    ...paths.files.flatMap((file) => mount(file.path, file.to)),
    ...(paths.env === undefined ? [] : ["--env-file", paths.env]),
    // A helper of the worker's own image runs the worker's node on its program, in place of the image's entrypoint.
    ...(plan.program === undefined ? [] : ["--entrypoint", NODE]),
    plan.image,
    ...(plan.program ?? []),
    ...(plan.prepared.config === undefined ? [] : [plan.prepared.config.to]),
    ...catalogFixedArgv(entry.run.extraArgs.filter((id) => id in CATALOG_FIXED_ARGS)),
  ];
}

/** The `docker run` arguments of a short-lived container of the worker's own image on the services network: hardened like a helper (no capability, no writable root, small limits), named, and labelled so the sweep finds it. */
function hardenedProgramRun(net: Pick<ServicesNetwork, "name" | "labelArgs">, probeImage: string, name: string, program: string[], envFile?: string, mounts: readonly string[] = []): string[] {
  return [
    "run", "--rm", "--name", name, "--stop-timeout", "1", "--pull=never", ...net.labelArgs(), "--network", net.name,
    "--user", "1000:1000", "--cap-drop", "ALL", "--security-opt", "no-new-privileges", "--read-only",
    "--memory", "64m", "--memory-swap", "64m", "--cpus", "0.25", "--pids-limit", "32", "--log-driver", "none",
    ...mounts,
    ...(envFile === undefined ? [] : ["--env-file", envFile]),
    "--entrypoint", NODE, probeImage, PROBE_ENTRY, ...program,
  ];
}

/** The probe container's `docker run` arguments: the worker's own image, hardened like a helper, on the services network, labelled so the sweep finds it. */
function probeArgs(net: ServicesNetwork, probeImage: string, address: string, entry: CatalogEntry, name: string): string[] {
  const health = entry.health;
  if (health.kind === "command") throw new RangeError("not a probe check");
  return hardenedProgramRun(net, probeImage, name, ["--host", address, "--port", String(health.port), ...(health.kind === "http" ? ["--path", health.path] : [])]);
}

const PROBE_NAME = /^[a-z0-9][a-z0-9_.-]{0,127}$/u;
const CONTROL_PATH = /^\/[A-Za-z0-9._~/-]{1,127}$/u;

/**
 * The arguments of one control call (a POST with the run's control token) to a helper, made from a probe-style container: the worker cannot reach an `rvi*` bridge itself. The token is NOT an argument: it is in the
 * env file the caller wrote on the run's tmpfs (`--env-file`), and the probe program reads it from its environment. Every input is checked here; a bad one throws.
 */
export function controlCallArgs(net: Pick<ServicesNetwork, "name" | "gateway" | "labelArgs">, input: { probeImage: string; address: string; port: number; path: string; name: string; envFile: string }): string[] {
  if (!IMAGE_REFERENCE.test(input.probeImage) || !PROBE_NAME.test(input.name) || !CONTROL_PATH.test(input.path) || input.path.split("/").includes("..")) throw new RangeError("a control call");
  if (!Number.isInteger(input.port) || input.port < 1 || input.port > 65_535 || !/^\d{1,3}(?:\.\d{1,3}){3}$/u.test(input.address) || !input.address.startsWith(net.gateway.slice(0, net.gateway.lastIndexOf(".") + 1))) throw new RangeError("a control call");
  if (!HOST_PATH.test(input.envFile) || input.envFile.split("/").includes("..") || input.envFile.includes("//")) throw new RangeError("a control call");
  return hardenedProgramRun(net, input.probeImage, input.name, ["--host", input.address, "--port", String(input.port), "--path", input.path, "--post"], input.envFile);
}

/** The emulator's control paths a control request may name (the fork's `RovaraControlController`): nothing else is ever sent with the control token. */
export const EMULATOR_CONTROL_PATHS = { reset: "/_rovara/reset", seed: "/_rovara/seed", ledgerSummary: "/_rovara/ledger/summary" } as const;
const BODY_TARGET = "/rovara/body.json";

/**
 * The arguments of one control request to the emulator (`POST /_rovara/seed` with a body, `GET /_rovara/ledger/summary` with its answer printed), made like `controlCallArgs` from a hardened container of the worker's image
 * on the services network. The token is in the env file (`--env-file`), never an argument. The body (a seed document that names the project's resources) is a file of the run's directory mounted read-only, never an argument,
 * and the path, method and timeout are fixed words and numbers: no repository string reaches a docker option.
 */
export function controlRequestArgs(net: Pick<ServicesNetwork, "name" | "gateway" | "labelArgs">, input: { probeImage: string; address: string; port: number; path: string; method: "GET" | "POST"; name: string; envFile: string; bodyFile?: string; print?: boolean; timeoutMs?: number }): string[] {
  const known: readonly string[] = Object.values(EMULATOR_CONTROL_PATHS);
  if (!known.includes(input.path) || (input.method !== "GET" && input.method !== "POST") || (input.method === "GET" && input.bodyFile !== undefined)) throw new RangeError("a control call");
  if (input.timeoutMs !== undefined && !(Number.isInteger(input.timeoutMs) && input.timeoutMs >= 100 && input.timeoutMs <= 30_000)) throw new RangeError("a control call");
  if (input.bodyFile !== undefined && (!HOST_PATH.test(input.bodyFile) || input.bodyFile.split("/").includes("..") || input.bodyFile.includes("//"))) throw new RangeError("a control call");
  // The shared checks (image, name, address, port, env file) are `controlCallArgs`'s own; it throws for a bad one, and its arguments are rebuilt below with the options this call adds.
  controlCallArgs(net, { probeImage: input.probeImage, address: input.address, port: input.port, path: input.path, name: input.name, envFile: input.envFile });
  const program = ["--host", input.address, "--port", String(input.port), "--path", input.path, "--control", input.method, ...(input.timeoutMs === undefined ? [] : ["--timeout-ms", String(input.timeoutMs)]), ...(input.bodyFile === undefined ? [] : ["--body-file", BODY_TARGET]), ...(input.print === true ? ["--print"] : [])];
  return hardenedProgramRun(net, input.probeImage, input.name, program, input.envFile, input.bodyFile === undefined ? [] : ["-v", `${input.bodyFile}:${BODY_TARGET}:ro`]);
}

// ---- health

type Call = (args: string[], timeoutMs?: number) => Promise<{ exitCode: number | null; stdout: string; stderr: string; timedOut?: boolean | undefined }>;

export interface HealthSubject {
  probeImage: string;
  entry: CatalogEntry;
  /** The dependency id and the helper's address and container name. */
  id: string;
  address: string;
  container: string;
  /** Makes the probe container's name: one number per question of this run. */
  probeNumber: number;
}

/**
 * One health question about a helper, with at most `limitMs` to answer: a `command` check is a fixed `docker exec` inside the helper; a `tcp` or `http` check is asked from a named probe container on the services network. A
 * probe that never answers, or whose call times out, is removed by name here; `inFlight` (when given) lists the probes not yet finished, so a cleanup can remove them too.
 */
async function askHealth(call: Call, net: ServicesNetwork, subject: HealthSubject, limitMs: number, inFlight?: Set<string>): Promise<boolean> {
  const health = subject.entry.health;
  if (health.kind === "command") {
    const result = await call(["exec", subject.container, ...healthCommand(subject.entry, health.check, subject.entry.run.ports[0] ?? 0)], Math.min(EXEC_CALL_TIMEOUT_MS, limitMs));
    // A cache that wants a password still answers: that is a live server.
    return result.exitCode === 0 || (health.check === "redis_ping" && /NOAUTH/u.test(result.stdout));
  }
  const name = probeContainerName(net, subject.id, subject.probeNumber);
  inFlight?.add(name);
  const result = await call(probeArgs(net, subject.probeImage, subject.address, subject.entry, name), Math.min(PROBE_CALL_TIMEOUT_MS, limitMs));
  if (result.timedOut === true || result.exitCode === null || result.exitCode === -1) await call(["rm", "--force", "--volumes", name]);
  inFlight?.delete(name);
  return result.exitCode === 0;
}

/** Asks a running helper its health question again (a session's `probe`, a reset's wait). Never throws: a Docker failure is "not healthy". */
export function askHelperHealth(docker: DockerCli, net: ServicesNetwork, subject: HealthSubject, limitMs: number = PROBE_CALL_TIMEOUT_MS): Promise<boolean> {
  const call: Call = (args, timeoutMs = DOCKER_CALL_TIMEOUT_MS) => docker.run(args, { timeoutMs }).catch((error: unknown) => ({ exitCode: -1, stdout: "", stderr: error instanceof Error ? error.message : String(error), timedOut: false }));
  return askHealth(call, net, subject, Math.max(1, limitMs));
}

// ---- starting

/**
 * Starts the helpers of a run on its services network. Every request is checked first (nothing is started or written if any is refused); then the helpers start level by level in dependency order, each level
 * waiting for health before the next. On any failure everything started is removed and a `HelperStartError` with a fixed sentence is thrown.
 */
export async function startHelpers(docker: DockerCli, net: ServicesNetwork, input: StartHelpersInput): Promise<StartedHelpers> {
  const plans = planHelpers(net, input);
  const levels = startLevels(plans);
  const now = input.now ?? Date.now;
  const sleep = input.sleep ?? ((ms: number) => new Promise<void>((done) => setTimeout(done, ms)));
  const call = (args: string[], timeoutMs = DOCKER_CALL_TIMEOUT_MS) => docker.run(args, { timeoutMs }).catch((error: unknown) => ({ exitCode: -1, stdout: "", stderr: error instanceof Error ? error.message : String(error), timedOut: false as boolean | undefined }));
  const attempted: string[] = [];
  const written: string[] = [];
  /** Files of helpers whose reset is a `restart`: Docker re-reads their bind sources when the container restarts, so they stay until `stop()`. The env file is not among them (a restart keeps the container's environment). */
  const keptUntilStop = new Set<string>();
  const started: StartedHelper[] = [];
  const runStart = now();

  const removeFile = async (name: string): Promise<void> => { await input.files.remove(name).catch(() => undefined); };
  const removeContainers = async (): Promise<void> => {
    const names = [...attempted, ...probesInFlight];
    probesInFlight.clear();
    if (names.length > 0) await call(["rm", "--force", "--volumes", ...names]);
  };
  const cleanUp = async (): Promise<void> => {
    await removeContainers();
    for (const name of written.splice(0)) await removeFile(name);
  };
  const fail = async (reason: HelperFailureReason, plan: Plan, sentence: string): Promise<never> => {
    await cleanUp();
    throw new HelperStartError(reason, sentence, plan.request.id);
  };

  const startOne = async (plan: Plan): Promise<number> => {
    const container = helperContainerName(net, plan.request.id);
    const startedAt = now();
    const files = [] as Array<{ path: string; to: string }>;
    let envPath: string | undefined;
    let configPath: string | undefined;
    try {
      if (plan.prepared.env.length > 0) {
        const name = `${container}.env`;
        written.push(name);
        envPath = await input.files.write(name, `${plan.prepared.env.join("\n")}\n`, 0o600);
      }
      if (plan.prepared.config !== undefined) {
        const name = `${container}.conf`;
        written.push(name);
        if (plan.entry.reset.kind === "restart") keptUntilStop.add(name);
        configPath = await input.files.write(name, plan.prepared.config.content, 0o644);
      }
      for (const file of plan.files) {
        const name = `${container}.${file.name}`;
        written.push(name);
        if (plan.entry.reset.kind === "restart") keptUntilStop.add(name);
        files.push({ path: await input.files.write(name, file.content, 0o644), to: file.to });
      }
      attempted.push(container);
      const args = runArgs(net, plan, container, { ...(envPath === undefined ? {} : { env: envPath }), ...(configPath === undefined ? {} : { config: configPath }), files });
      const result = await call(args);
      if (result.exitCode !== 0) return await fail("start_failed", plan, `${plan.name} could not be started`);
    } catch (error) {
      if (error instanceof HelperStartError) throw error;
      return await fail("start_failed", plan, `${plan.name} could not be started`);
    } finally {
      // Docker has read the env file by now (or the start failed): it does not stay.
      if (envPath !== undefined) {
        await removeFile(`${container}.env`);
        const at = written.indexOf(`${container}.env`);
        if (at >= 0) written.splice(at, 1);
      }
    }
    return startedAt;
  };

  let probeNumber = 0;
  const probesInFlight = new Set<string>();
  /** One health question, with at most `limitMs` to answer. A probe container is named, so one that never answers (or whose call times out) is removed by name and cannot outlive the wait. */
  const healthy = (plan: Plan, container: string, limitMs: number): Promise<boolean> => {
    probeNumber += 1;
    return askHealth(call, net, { probeImage: input.probeImage, entry: plan.entry, id: plan.request.id, address: plan.address, container, probeNumber }, limitMs, probesInFlight);
  };

  const aborted = (): boolean => input.signal?.aborted === true;
  const waitHealthy = async (plan: Plan, startedAt: number): Promise<void> => {
    const container = helperContainerName(net, plan.request.id);
    const entryDeadline = startedAt + plan.entry.health.startTimeoutS * 1_000;
    const runDeadline = runStart + RUN_HEALTH_LIMIT_S * 1_000;
    const deadline = Math.min(entryDeadline, runDeadline);
    for (;;) {
      if (aborted()) return fail("stopped", plan, `${plan.name} was stopped while starting`);
      // A hard ceiling: checked before every attempt, and no call is given more time than is left.
      const remainingMs = deadline - now();
      if (remainingMs <= 0) {
        const seconds = entryDeadline <= runDeadline ? plan.entry.health.startTimeoutS : Math.max(1, Math.ceil((runDeadline - startedAt) / 1_000));
        return fail("health_timeout", plan, `${plan.name} did not start (health check timed out after ${String(seconds)} s)`);
      }
      const state = await call(["inspect", "--format", "{{.State.Status}}", container], Math.min(EXEC_CALL_TIMEOUT_MS, remainingMs));
      if (state.exitCode !== 0 || state.stdout.trim() !== "running") return fail("exited", plan, `${plan.name} stopped while starting`);
      if (await healthy(plan, container, Math.max(1, deadline - now()))) return;
      if (aborted()) return fail("stopped", plan, `${plan.name} was stopped while starting`);
      await sleep(Math.max(1, Math.min(HEALTH_POLL_MS, deadline - now())));
    }
  };

  /**
   * An image that declares a volume (`VOLUME` in its Dockerfile) gets an anonymous disk volume at that path unless something is mounted there, and that volume would hold data past the run. So before anything starts, every
   * volume a pinned image declares must be covered by one of the entry's tmpfs mounts (the same destination path: a folder under one is a different mount point and is not enough); otherwise the image is refused. An image that cannot be inspected is refused too.
   */
  const assertVolumesCovered = async (plan: Plan): Promise<void> => {
    const inspected = await call(["image", "inspect", "--format", "{{json .Config.Volumes}}", plan.image]);
    let declared: string[];
    try {
      const parsed: unknown = inspected.exitCode === 0 ? JSON.parse(inspected.stdout.trim()) : undefined;
      if (parsed === undefined) throw new RangeError("unreadable");
      if (parsed === null) declared = [];
      else if (typeof parsed === "object" && !Array.isArray(parsed)) declared = Object.keys(parsed);
      else throw new RangeError("unreadable");
    } catch {
      throw refused(plan.request);
    }
    const covered = (path: string): boolean => plan.entry.run.tmpfs.some((mount) => path === mount.path);
    if (declared.some((path) => !covered(path))) throw refused(plan.request);
  };

  try {
    const checkedImages = new Set<string>();
    for (const plan of plans) {
      if (checkedImages.has(plan.image)) continue;
      checkedImages.add(plan.image);
      await assertVolumesCovered(plan);
    }
    for (const level of levels) {
      const startTimes = new Map<Plan, number>();
      for (const plan of level) startTimes.set(plan, await startOne(plan));
      for (const plan of level) {
        await waitHealthy(plan, startTimes.get(plan)!);
        started.push({ id: plan.request.id, container: helperContainerName(net, plan.request.id), address: plan.address, aliases: plan.aliases, ports: [...plan.entry.run.ports] });
      }
    }
  } catch (error) {
    if (error instanceof HelperStartError) throw error;
    await cleanUp();
    throw agentXError("RUNTIME_UNAVAILABLE", "AgentX could not start the test services");
  }
  // Healthy: the files a helper read at start are not needed any more.
  for (const name of written.splice(0)) if (!keptUntilStop.has(name)) await removeFile(name);
  const order = new Map(plans.map((plan) => [plan.request.id, plan.index]));
  started.sort((a, b) => order.get(a.id)! - order.get(b.id)!);
  let stopped = false;
  return {
    helpers: started,
    async stop() {
      if (stopped) return;
      stopped = true;
      await removeContainers();
      for (const name of keptUntilStop) await removeFile(name);
      keptUntilStop.clear();
    },
  };
}
