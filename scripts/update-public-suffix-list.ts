// Regenerates packages/contracts/src/public-suffix-rules.ts from a pinned commit of https://github.com/publicsuffix/list.
// Usage: node scripts/update-public-suffix-list.ts <40-char commit sha>
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const COMMIT_PATTERN = /^[0-9a-f]{40}$/;
// One bare brand-TLD rule is omitted from the checked-in copy (the default `*` rule gives the same result).
const OMITTED_RULES = new Set(["aws"]);

export function parsePublicSuffixList(rawText: string): string[] {
  const rules = new Set<string>();
  for (const rawLine of rawText.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (line === "" || line.startsWith("//")) continue;
    const rule = line.split(/\s+/)[0];
    if (rule === undefined || rule === "" || OMITTED_RULES.has(rule)) continue;
    rules.add(rule);
  }
  return [...rules].sort();
}

export function renderPublicSuffixRulesModule(commit: string, sortedRules: readonly string[]): string {
  const escaped = sortedRules.join("\n").replaceAll("\\", "\\\\").replaceAll("`", "\\`").replaceAll("${", "\\${");
  return [
    "// GENERATED by scripts/update-public-suffix-list.ts: do not edit by hand.",
    `// Source: https://github.com/publicsuffix/list/blob/${commit}/public_suffix_list.dat`,
    `// Commit: ${commit}`,
    `// Rules: ${sortedRules.length} (ICANN and PRIVATE sections; a leading "*." is a wildcard rule, a leading "!" an exception rule).`,
    "// One brand-top-level-domain rule is left out of the checked-in copy (it is a bare TLD, so the default rule `*` gives the same answer for it).",
    "// Regenerate: node scripts/update-public-suffix-list.ts <commit>, at a commit no newer than two weeks old.",
    "",
    `export const PUBLIC_SUFFIX_LIST_COMMIT = "${commit}";`,
    "",
    `const RAW_PUBLIC_SUFFIX_RULES = \`${escaped}\`;`,
    "",
    "let cachedRules: ReadonlySet<string> | undefined;",
    "",
    "/** Returns the read-only, frozen Public Suffix List rule set, constructed lazily on first access. */",
    "export function getPublicSuffixRules(): ReadonlySet<string> {",
    "  if (cachedRules !== undefined) return cachedRules;",
    '  const rules = new Set<string>(RAW_PUBLIC_SUFFIX_RULES.split("\\n"));',
    "  // The set decides what a project may let its machines reach, so nothing at runtime may change it.",
    '  for (const method of ["add", "delete", "clear"] as const) {',
    '    Object.defineProperty(rules, method, { value: () => { throw new TypeError("the public suffix list is read-only"); } });',
    "  }",
    "  cachedRules = Object.freeze(rules);",
    "  return cachedRules;",
    "}",
    "",
  ].join("\n");
}

async function main(): Promise<void> {
  const commit = process.argv[2];
  if (commit === undefined || !COMMIT_PATTERN.test(commit)) {
    throw new Error("usage: node scripts/update-public-suffix-list.ts <40-char commit sha>");
  }
  const url = `https://raw.githubusercontent.com/publicsuffix/list/${commit}/public_suffix_list.dat`;
  const response = await fetch(url);
  if (!response.ok) throw new Error(`Failed to fetch ${url}: ${response.status} ${response.statusText}`);
  const rules = parsePublicSuffixList(await response.text());
  const outPath = resolve("packages/contracts/src/public-suffix-rules.ts");
  writeFileSync(outPath, renderPublicSuffixRulesModule(commit, rules), "utf8");
  console.log(`Wrote ${outPath}: ${rules.length} rules from commit ${commit}.`);
}

if (process.argv[1]?.endsWith("update-public-suffix-list.ts")) {
  await main();
}
